TARG_INT
TARG_INT_Most_Sig_One(
  TARG_INT x
)
{
  INT i;

  /* Find the least significant byte in x that's not zero and look it
   * up in the above table.
   */
  for (i = sizeof(x) - 1; i >= 0; --i ) {
    unsigned char y = ((TARG_UINT) x) >> (((UINT) i) * 8);

    if (y != 0 )
      return i*8 + UINT8_most_sig_one[y];
  }

  return (TARG_INT) -1;
}


